#!/usr/bin/env python3
"""Readability and maintainability signals for one branch, each tied to a maintainer rule.

Every flag is (a) a number or fact this script computed from the diff and the two blobs
(base and branch) and (b) a rule from review/context/history.json with its source links.
Numbers with no rule behind them go in `measures` and never become a flag. A flag is a
signal for a reviewer, not a verdict.

Scope: files changed by `git diff 32258fdb...origin/<branch>`, skipping tests/**/Resources/**
(generator snapshots). Old side = merge base of 32258fdb and the branch.

Measures (all base vs branch):
  methods      C# methods the diff touches, in non-generated .cs files: line count, max brace
               depth (method body = 1), count of if / else / case / && / || (cyclomatic proxy;
               `else if` counts once as else and once as if), plus clone_complexity.py's estimate
               (1 + decision tokens). No maintainer rule covers method size or nesting, so these
               are measures only.
  duplication  clone_complexity.py's line-window clone detector (window 6, its default) per
               changed non-generated .cs file, and identical added blocks (the normalised added
               lines of one hunk) that occur 2+ times across in-scope files. Flag: H-20, for
               src/ files only (tests are reported as measures).
  #if          preprocessor `#if` directives added to non-generated, non-template C#
               (directives inside string literals are not counted). Flag: H-11.
  T4           per .tt file: control code blocks (<# ... #> containing if/else/foreach/for/while/
               switch) and preprocessor lines the template emits as text (#if/#elif/#else/#endif).
               Flag: H-07 when either goes up.
  generated    a generated .cs (a sibling .tt exists, or the header says <auto-generated>) changed
               without its .tt changing in the same diff. Flag: H-06. When both changed, the
               pair is listed as "template and output changed together" (a measure; cites
               evidence/<branch>/template-regeneration.json when that file exists).
  tests        whether the diff adds or changes tests, test methods added, and for each claim
               whether evidence/<branch>/confidence.json backs it with a flip-test or revert-test.
               Flag: H-15 only when src changes and the diff adds or changes no test file. Per-claim test support is a measure:
               many claims are reviewer findings, not new behaviour, so H-15 does not apply to them.

Thresholds: none from the maintainers. Ours: the clone window (6 normalised lines, inherited from
clone_complexity.py), "2+ occurrences" for a repeated added block, and "any increase" for a flag.

Method parser limits (a light brace matcher, not a C# parser):
  * strings (regular, verbatim, raw, interpolated), char literals and comments are blanked first;
    interpolation holes are blanked too, and nested quotes inside a hole of a non-raw interpolated
    string are tracked only one level deep;
  * a block is a method when its header (text since the last ; { or }) sits directly in a type,
    and has `name(` after leading attributes are removed, with no `=` before the `(`; property
    accessors (get/set/init/add/remove) count as methods named Prop.get etc.; expression-bodied
    members (`) =>` ... `;`) are methods too; operators, indexers and local functions are not
    separated (a local function counts as part of its method);
  * a method's span starts at its first attribute line and ends at its closing brace;
  * depth counts braces only, so a braceless `if (x) y;` adds no depth;
  * #if branches are not evaluated: both arms are parsed, so unbalanced braces across #if arms
    can confuse it;
  * base and branch methods are matched by type, name and parameter text; a changed signature
    shows as one removed and one added method.

    python3 review/scripts/readability.py --repo <clone> --branch ju26-issue-2234 [--write]
Python 3, standard library only; reads blobs with `git show`, never checks out.
"""
import argparse, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REVIEW = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from claim_coverage import BASE, parse_part, covered  # noqa: E402
from clone_complexity import DECISION, clones, normalise  # noqa: E402

WINDOW = 6
PROXY = [("if", re.compile(r"\bif\b")), ("else", re.compile(r"\belse\b")), ("case", re.compile(r"\bcase\b")),
         ("&&", re.compile(r"&&")), ("||", re.compile(r"\|\|"))]
KEYWORDS = {"if", "for", "foreach", "while", "switch", "catch", "using", "lock", "fixed", "return", "new",
            "typeof", "nameof", "sizeof", "default", "checked", "unchecked", "when", "base", "this", "throw"}
ACCESSORS = {"get", "set", "init", "add", "remove"}
FLIP_KINDS = {"flip-test", "revert-test"}


def git(repo, *args, ok_fail=False):
    p = subprocess.run(["git", "-C", repo, *args], capture_output=True, text=True)
    if p.returncode:
        if ok_fail:
            return None
        raise SystemExit(p.stderr)
    return p.stdout


def show(repo, rev, path):
    return git(repo, "show", f"{rev}:{path}", ok_fail=True)


# ---------------------------------------------------------------- diff

def parse_diff(repo, branch):
    """{path: {"old": path_or_None, "added": [new line nos], "deleted": [old line nos], "hunks": [...]}}"""
    out = git(repo, "diff", "-U0", "--no-color", f"{BASE}...origin/{branch}")
    files, cur, old_path = {}, None, None
    h = None
    for line in out.splitlines():
        if line.startswith("diff --git"):
            cur, h = None, None
        elif line.startswith("--- "):
            p = line[4:]
            old_path = None if p == "/dev/null" else p[2:]
        elif line.startswith("+++ "):
            p = line[4:]
            new_path = None if p == "/dev/null" else p[2:]
            key = new_path or old_path
            cur = files.setdefault(key, {"old": old_path, "new": new_path, "added": [], "deleted": [], "hunks": []})
        elif line.startswith("@@") and cur is not None:
            m = re.match(r"@@ -(\d+)(?:,(\d+))? \+(\d+)(?:,(\d+))? @@", line)
            o, n = int(m.group(1)), int(m.group(3))
            nc = int(m.group(4) or "1")
            h = {"start": n, "end": n + max(nc, 1) - 1, "o": o, "n": n, "added": [], "deleted": []}
            cur["hunks"].append(h)
        elif h is not None and line.startswith("+"):
            cur["added"].append(h["n"]); h["added"].append((h["n"], line[1:])); h["n"] += 1
        elif h is not None and line.startswith("-"):
            cur["deleted"].append(h["o"]); h["deleted"].append((h["o"], line[1:])); h["o"] += 1
    return files


# ---------------------------------------------------------------- C# blanking

def blank_csharp(text):
    """Return (lines, directives): code lines with strings/comments/directives replaced by spaces,
    and {line_no: directive_text} for preprocessor lines that start in code."""
    out, directives = [], {}
    i, n = 0, len(text)
    state = "code"  # code | line | block | str | vstr | raw | chr | istr
    raw_q = 0
    interp = []  # stack for interpolated strings: [depth, verbatim, nested_quote]
    buf = []
    line_no = 1
    at_line_start = True

    def emit(c):
        buf.append(c)

    while i < n:
        c = text[i]
        if c == "\n":
            if state == "line":
                state = "code"
            out.append("".join(buf)); buf = []
            line_no += 1
            at_line_start = True
            i += 1
            continue
        if state == "code" and at_line_start:
            j = i
            while j < n and text[j] in " \t﻿":
                j += 1
            if j < n and text[j] == "#":
                k = text.find("\n", j)
                k = n if k < 0 else k
                directives[line_no] = text[j:k].strip()
                buf.append(" " * (k - i))
                i = k
                continue
        at_line_start = False
        nxt = text[i + 1] if i + 1 < n else ""
        if state == "code":
            if c == "/" and nxt == "/":
                state = "line"; emit(" "); i += 1; continue
            if c == "/" and nxt == "*":
                state = "block"; emit("  "); i += 2; continue
            m = re.match(r'(\$*)(@?)("{3,})', text[i:i + 12]) if c in '$"@' else None
            if m and len(m.group(3)) >= 3 and not m.group(2):
                raw_q = len(m.group(3)); state = "raw"
                buf.append(" " * len(m.group(0))); i += len(m.group(0)); continue
            if c == "$" and text[i + 1:i + 3] in ('@"',) or c == "@" and text[i + 1:i + 3] == '$"':
                interp.append([0, True, False]); state = "istr"; buf.append("   "); i += 3; continue
            if c == "$" and nxt == '"':
                interp.append([0, False, False]); state = "istr"; buf.append("  "); i += 2; continue
            if c == "@" and nxt == '"':
                state = "vstr"; buf.append("  "); i += 2; continue
            if c == '"':
                state = "str"; emit(" "); i += 1; continue
            if c == "'":
                m = re.match(r"'(?:\\.[^']*|[^'\\])'", text[i:i + 12])
                if m:
                    buf.append(" " * len(m.group(0))); i += len(m.group(0)); continue
            emit(c); i += 1; continue
        if state == "line":
            emit(" "); i += 1; continue
        if state == "block":
            if c == "*" and nxt == "/":
                state = "code"; emit("  "); i += 2; continue
            emit(" "); i += 1; continue
        if state == "str":
            if c == "\\":
                buf.append("  " if nxt and nxt != "\n" else " "); i += 2 if nxt and nxt != "\n" else 1; continue
            if c == '"':
                state = "code"
            emit(" "); i += 1; continue
        if state == "vstr":
            if c == '"' and nxt == '"':
                buf.append("  "); i += 2; continue
            if c == '"':
                state = "code"
            emit(" "); i += 1; continue
        if state == "raw":
            if text.startswith('"' * raw_q, i):
                state = "code"; buf.append(" " * raw_q); i += raw_q; continue
            emit(" "); i += 1; continue
        if state == "istr":
            top = interp[-1]
            if top[2]:  # inside a nested string within a hole
                if c == "\\":
                    buf.append("  "); i += 2; continue
                if c == '"':
                    top[2] = False
                emit(" "); i += 1; continue
            if top[0] == 0:
                if c == "{" and nxt == "{":
                    buf.append("  "); i += 2; continue
                if c == "{":
                    top[0] = 1; emit(" "); i += 1; continue
                if not top[1] and c == "\\":
                    buf.append("  "); i += 2; continue
                if top[1] and c == '"' and nxt == '"':
                    buf.append("  "); i += 2; continue
                if c == '"':
                    interp.pop(); state = "code" if not interp else "istr"
                emit(" "); i += 1; continue
            # in a hole
            if c == "{":
                top[0] += 1
            elif c == "}":
                top[0] -= 1
            elif c == '"':
                top[2] = True
            emit(" "); i += 1; continue
    out.append("".join(buf))
    return out, directives


def strip_attributes(h):
    h = h.strip()
    while h.startswith("["):
        d = 0
        for k, ch in enumerate(h):
            d += ch == "["
            d -= ch == "]"
            if d == 0:
                h = h[k + 1:].strip()
                break
        else:
            return h
    return h


def method_sig(header):
    """(name, params) when header looks like a method/ctor declaration, else None."""
    h = strip_attributes(" ".join(header.split()))
    p = h.find("(")
    if p < 0 or "=" in h[:p] or re.search(r"\boperator\b", h[:p]):
        return None
    m = re.search(r"([A-Za-z_]\w*)\s*(?:<[^()]*>)?\s*$", h[:p])
    if not m or m.group(1) in KEYWORDS:
        return None
    if re.match(r"^(?:if|for|foreach|while|switch|catch|using|lock|fixed|else|do|try|finally)\b", h):
        return None
    d, q = 0, p
    for q in range(p, len(h)):
        d += h[q] == "("
        d -= h[q] == ")"
        if d == 0:
            break
    return m.group(1), " ".join(h[p + 1:q].split())


def parse_methods(text):
    """List of methods: {key, name, start, end, depth} (1-based lines)."""
    lines, directives = blank_csharp(text)
    stack = []  # entries: {kind, name, start, depth_rel, max}
    header, header_start = [], None
    methods = []
    for ln, line in enumerate(lines, 1):
        for ch in line:
            if ch == "{":
                hdr = "".join(header)
                parent = stack[-1] if stack else None
                kind, name = "block", None
                m_type = re.search(r"\b(class|struct|interface|record|enum)\s+([A-Za-z_]\w*)", strip_attributes(hdr))
                if re.search(r"\bnamespace\b", hdr):
                    kind = "ns"
                elif m_type and (parent is None or parent["kind"] in ("ns", "type")) and "(" not in hdr.split(m_type.group(0))[0]:
                    kind, name = "type", m_type.group(2)
                elif parent and parent["kind"] == "type":
                    sig = method_sig(hdr)
                    if sig:
                        kind, name = "method", sig
                    elif re.search(r"[A-Za-z_]\w*\s*$", strip_attributes(hdr)) and "=" not in hdr and "(" not in hdr:
                        kind, name = "prop", re.search(r"([A-Za-z_]\w*)\s*$", strip_attributes(hdr)).group(1)
                elif parent and parent["kind"] == "prop" and hdr.strip().split()[-1:] and hdr.strip().split()[-1] in ACCESSORS:
                    kind, name = "method", (parent["name"] + "." + hdr.strip().split()[-1], "")
                entry = {"kind": kind, "name": name, "start": header_start or ln, "type": None, "depth": 0, "max": 0}
                if kind == "method":
                    entry["type"] = next((s["name"] for s in reversed(stack) if s["kind"] == "type"), None)
                    entry["depth"] = 1
                    entry["max"] = 1
                else:
                    meth = next((s for s in reversed(stack) if s["kind"] == "method"), None)
                    if meth is not None:
                        meth["depth"] += 1
                        meth["max"] = max(meth["max"], meth["depth"])
                stack.append(entry)
                header, header_start = [], None
            elif ch == "}":
                if stack:
                    e = stack.pop()
                    if e["kind"] == "method":
                        methods.append({"type": e["type"], "name": e["name"][0], "params": e["name"][1],
                                        "start": e["start"], "end": ln, "depth": e["max"]})
                    else:
                        meth = next((s for s in reversed(stack) if s["kind"] == "method"), None)
                        if meth is not None:
                            meth["depth"] -= 1
                header, header_start = [], None
            elif ch == ";":
                hdr = "".join(header)
                parent = stack[-1] if stack else None
                if parent and parent["kind"] == "type" and re.search(r"\)\s*(?:where\b[^=]*)?=>", hdr):
                    sig = method_sig(hdr.split("=>")[0])
                    if sig:
                        methods.append({"type": parent["name"], "name": sig[0], "params": sig[1],
                                        "start": header_start or ln, "end": ln, "depth": 0})
                elif parent and parent["kind"] == "prop" and hdr.strip().split()[:1] and hdr.strip().split()[0] in ACCESSORS and "=>" in hdr:
                    methods.append({"type": None, "name": parent["name"] + "." + hdr.strip().split()[0], "params": "",
                                    "start": header_start or ln, "end": ln, "depth": 0})
                header, header_start = [], None
            else:
                if header_start is None and not ch.isspace():
                    header_start = ln
                header.append(ch)
        header.append(" ")
    for m in methods:
        m["key"] = f"{m['type']}.{m['name']}({m['params']})"
        body = lines[m["start"] - 1:m["end"]]
        m["lines"] = m["end"] - m["start"] + 1
        m["proxy"] = {k: sum(len(rx.findall(l)) for l in body) for k, rx in PROXY}
        m["proxy_total"] = sum(m["proxy"].values())
        m["estimate"] = 1 + sum(len(rx.findall(l)) for l in body for _, rx in DECISION)
    return methods, lines, directives


# ---------------------------------------------------------------- T4

def t4_scan(text):
    """Counts for a .tt file: control blocks, their line numbers, and emitted preprocessor lines."""
    control_lines, code_block_lines, emitted = set(), set(), {}
    pos, ln = 0, 1
    for m in re.finditer(r"<#([@=+]?)(.*?)#>", text, re.S):
        seg = text[pos:m.start()]
        # text region: emitted output lines
        start_ln = ln
        for k, l in enumerate(seg.split("\n")):
            line_here = start_ln + k
            if (k > 0 or pos == 0 or text[pos - 1] == "\n") and re.match(r"^\s*#\s*(if|elif|else|endif)\b", l):
                emitted[line_here] = l.strip()
        ln += seg.count("\n")
        body_start = ln
        ln += m.group(0).count("\n")
        if m.group(1) in ("", "+"):
            rng = set(range(body_start, ln + 1))
            code_block_lines |= rng
            if re.search(r"\b(if|else|foreach|for|while|switch)\b", m.group(2)):
                control_lines |= rng
        pos = m.end()
    seg = text[pos:]
    for k, l in enumerate(seg.split("\n")):
        if (k > 0 or pos == 0 or text[pos - 1] == "\n") and re.match(r"^\s*#\s*(if|elif|else|endif)\b", l):
            emitted[ln + k] = l.strip()
    return {"control_block_lines": sorted(control_lines), "code_block_lines": sorted(code_block_lines),
            "emitted_preprocessor": emitted}


# ---------------------------------------------------------------- helpers

def ranges(nums):
    nums = sorted(set(nums))
    out = []
    for x in nums:
        if out and x == out[-1][1] + 1:
            out[-1][1] = x
        else:
            out.append([x, x])
    return [(a, b) for a, b in out]


def fmt_ranges(nums):
    return ",".join(f"{a}-{b}" if a != b else str(a) for a, b in ranges(nums))


def where_str(locs):
    """[(path, s, e)] -> 'path:a-b,c; path2' (one entry per file, ranges in line order)."""
    by = {}
    for p, s, e in locs:
        by.setdefault(p, []).extend(range(s, e + 1) if s else [])
    return "; ".join(f"{p}:{fmt_ranges(n)}" if n else p for p, n in by.items())


def is_generated(repo, rev_old, rev_new, path):
    if not path.endswith(".cs"):
        return False
    if path.endswith(".g.cs"):
        return True
    tt = path[:-3] + ".tt"
    if show(repo, rev_new, tt) is not None or show(repo, rev_old, tt) is not None:
        return True
    txt = show(repo, rev_new, path) or show(repo, rev_old, path) or ""
    return "<auto-generated" in txt[:800]


def claims_for(locs, claim_parts):
    """locs: [(file, start, end)] -> sorted claim ids covering any of them."""
    return sorted({cid for f, s, e in locs for cid, parts in claim_parts.items() if covered(f, s, e, parts)})


# ---------------------------------------------------------------- main

def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--repo", default=os.environ.get("MP_REPO"), required=os.environ.get("MP_REPO") is None)
    ap.add_argument("--branch", required=True)
    ap.add_argument("--write", action="store_true")
    a = ap.parse_args()
    repo = os.path.abspath(a.repo)

    hist = json.load(open(os.path.join(REVIEW, "context", "history.json")))
    rules = {r["id"]: r for r in hist["rules"]}
    dossier = json.load(open(os.path.join(REVIEW, "dossier", f"{a.branch}.json")))
    claim_parts = {c["id"]: [parse_part(p) for p in c.get("diff_parts", [])] for c in dossier["claims"]}
    conf_path = os.path.join(REVIEW, "evidence", a.branch, "confidence.json")
    conf = json.load(open(conf_path)) if os.path.exists(conf_path) else None

    head = git(repo, "rev-parse", f"origin/{a.branch}").strip()
    old = git(repo, "merge-base", BASE, head).strip()
    diff = parse_diff(repo, a.branch)

    flags, measures = [], {}

    def flag(measure, rule, vb, vr, locs, extra=None):
        r = rules[rule]
        f = {"id": f"RD-{a.branch.split('-')[-1]}-{len(flags) + 1:02d}", "measure": measure,
             "value_base": vb, "value_branch": vr,
             "where": where_str(locs),
             "rule": rule, "rule_text": r["rule"], "sources": r["sources"],
             "claims": claims_for([(p, s or 1, e or 10 ** 9) for p, s, e in locs], claim_parts)}
        if extra:
            f.update(extra)
        flags.append(f)

    in_scope = {p: d for p, d in diff.items() if not re.match(r"^tests/.*/Resources/", p)}
    skipped = sorted(p for p in diff if p not in in_scope)
    gen = {p: is_generated(repo, old, head, p) for p in in_scope}
    kinds = {}
    for p in in_scope:
        if p.endswith(".tt"):
            kinds[p] = "template"
        elif p.endswith(".cs"):
            kinds[p] = "generated" if gen[p] else ("test" if p.startswith("tests/") else "source")
        else:
            kinds[p] = "other (not measured)"
    measures["files"] = {"in_scope": {p: kinds[p] for p in sorted(in_scope)},
                         "skipped_snapshots": len(skipped)}

    # ---- methods
    meth_out = []
    blobs = {}
    for p, d in sorted(in_scope.items()):
        if kinds[p] not in ("source", "test"):
            continue
        bt = show(repo, old, d["old"]) if d["old"] else None
        nt = show(repo, head, d["new"]) if d["new"] else None
        blobs[p] = (bt, nt)
        bm = parse_methods(bt)[0] if bt else []
        nm, nlines, ndirs = parse_methods(nt) if nt else ([], [], {})
        bdirs = blank_csharp(bt)[1] if bt else {}
        blobs[p] = (bt, nt, bdirs, ndirs)
        touched = {}
        for m in nm:
            if any(m["start"] <= x <= m["end"] for x in d["added"]):
                touched.setdefault(m["key"], {})["branch"] = m
        for m in bm:
            if any(m["start"] <= x <= m["end"] for x in d["deleted"]):
                touched.setdefault(m["key"], {})["base"] = m
        bk = {m["key"]: m for m in bm}
        nk = {m["key"]: m for m in nm}
        for k in list(touched):
            touched[k].setdefault("base", bk.get(k))
            touched[k].setdefault("branch", nk.get(k))
        for k, v in sorted(touched.items(), key=lambda kv: (kv[1]["branch"] or kv[1]["base"])["start"]):
            def pick(m):
                return None if m is None else {"lines": m["lines"], "where": f"{p}:{m['start']}-{m['end']}",
                                               "max_brace_depth": m["depth"], "if_else_case_and_or": m["proxy_total"],
                                               "by_token": m["proxy"], "clone_complexity_estimate": m["estimate"]}
            e = {"method": k, "file": p, "base": pick(v["base"]), "branch": pick(v["branch"])}
            if v["base"] and v["branch"]:
                e["delta"] = {"lines": v["branch"]["lines"] - v["base"]["lines"],
                              "max_brace_depth": v["branch"]["depth"] - v["base"]["depth"],
                              "if_else_case_and_or": v["branch"]["proxy_total"] - v["base"]["proxy_total"]}
            ln = v["branch"] or v["base"]
            e["claims"] = claims_for([(p, ln["start"], ln["end"])], claim_parts) if v["branch"] else []
            meth_out.append(e)
    measures["methods_touched"] = {"rule": None, "note": "no maintainer rule in history.json covers method size, "
                                   "nesting or branch count, so these are measures, not flags", "methods": meth_out}

    # ---- duplication: window clones per non-generated C# file (clone_complexity.clones)
    dup = []
    for p, d in sorted(in_scope.items()):
        if kinds[p] not in ("source", "test") or not d["new"]:
            continue
        bt, nt = blobs[p][0], blobs[p][1]
        cb = clones(bt.splitlines(), WINDOW)[0] if bt else None
        cn, dup_lines = clones(nt.splitlines(), WINDOW)
        code_added = {n for n, _ in normalise(nt.splitlines()) if n in set(d["added"])}
        in_dup = sorted(x for x in code_added if x in dup_lines)
        e = {"file": p, "kind": kinds[p], "window": WINDOW,
             "duplicated_normalised_lines": {"base": cb["duplicated_normalised_lines"] if cb else 0,
                                             "branch": cn["duplicated_normalised_lines"]},
             "duplicated_blocks": {"base": cb["duplicated_blocks"] if cb else 0, "branch": cn["duplicated_blocks"]},
             "added_code_lines": len(code_added), "added_code_lines_in_duplicated_blocks": in_dup}
        dup.append(e)
        if kinds[p] == "source" and (e["duplicated_normalised_lines"]["branch"] > e["duplicated_normalised_lines"]["base"]):
            flag("duplicated normalised lines (clone_complexity.py line-window detector, window 6; window is ours)",
                 "H-20", e["duplicated_normalised_lines"]["base"], e["duplicated_normalised_lines"]["branch"],
                 [(p, a_, b_) for a_, b_ in ranges(in_dup)] or [(p, None, None)],
                 {"detail": f"{len(in_dup)} of {len(code_added)} added code lines sit in duplicated blocks; "
                            f"duplicated blocks {e['duplicated_blocks']['base']} -> {e['duplicated_blocks']['branch']}"})
    measures["duplication_window"] = dup

    # ---- duplication: identical added blocks across in-scope files
    groups = {}
    for p, d in in_scope.items():
        if kinds[p] not in ("source", "test", "template"):
            continue
        for h in d["hunks"]:
            if not h["added"]:
                continue
            norm = normalise([t for _, t in h["added"]])
            if not norm:
                continue
            key = "\n".join(t for _, t in norm)
            nos = [h["added"][i - 1][0] for i, _ in norm]
            groups.setdefault(key, []).append((p, min(nos), max(nos)))
    rep = []
    for key, locs in sorted(groups.items(), key=lambda kv: -len(kv[1])):
        if len(locs) < 2:
            continue
        rep.append({"block": key.splitlines(), "normalised_lines": len(key.splitlines()), "occurrences": len(locs),
                    "where": [f"{p}:{s}-{e}" for p, s, e in sorted(locs)]})
        src_locs = [l for l in locs if kinds[l[0]] in ("source", "template")]
        if len(src_locs) >= 2:
            flag("identical added block repeated in src (normalised lines of one hunk; '2+ times' is ours)",
                 "H-20", 0, len(src_locs), sorted(src_locs),
                 {"detail": f"{len(key.splitlines())} normalised line(s), added {len(src_locs)} times: "
                            + " | ".join(key.splitlines())[:300]})
    measures["repeated_added_blocks"] = rep

    # ---- #if in non-generated, non-template C#
    ifs = []
    for p, d in sorted(in_scope.items()):
        if kinds[p] not in ("source", "test") or not d["new"]:
            continue
        bdirs, ndirs = blobs[p][2], blobs[p][3]
        nb = sum(1 for t in bdirs.values() if re.match(r"#\s*if\b", t))
        nn = sum(1 for t in ndirs.values() if re.match(r"#\s*if\b", t))
        added_if = sorted(x for x in d["added"] if x in ndirs and re.match(r"#\s*if\b", ndirs[x]))
        ifs.append({"file": p, "kind": kinds[p], "if_directives": {"base": nb, "branch": nn}, "added_at": added_if})
        if added_if:
            flag("#if directives in non-generated, non-template C#", "H-11", nb, nn,
                 [(p, a_, b_) for a_, b_ in ranges(added_if)])
    measures["if_directives"] = ifs

    # ---- T4 templates
    t4 = []
    for p, d in sorted(in_scope.items()):
        if kinds[p] != "template":
            continue
        bt = show(repo, old, d["old"]) if d["old"] else ""
        nt = show(repo, head, d["new"]) if d["new"] else ""
        sb, sn = t4_scan(bt or ""), t4_scan(nt or "")
        added = set(d["added"])
        add_ctrl = sorted(added & set(sn["control_block_lines"]))
        add_code = sorted(added & set(sn["code_block_lines"]))
        add_pp = sorted(x for x in added if x in sn["emitted_preprocessor"])
        e = {"file": p,
             "control_block_lines": {"base": len(sb["control_block_lines"]), "branch": len(sn["control_block_lines"]),
                                     "added": len(add_ctrl)},
             "code_block_lines_added": len(add_code),
             "emitted_preprocessor_lines": {"base": len(sb["emitted_preprocessor"]), "branch": len(sn["emitted_preprocessor"]),
                                            "added": len(add_pp),
                                            "added_text": sorted({sn["emitted_preprocessor"][x] for x in add_pp})}}
        t4.append(e)
        if add_ctrl:
            flag("T4 control-block lines (<# if/else/foreach/for/while/switch #>)", "H-07",
                 e["control_block_lines"]["base"], e["control_block_lines"]["branch"],
                 [(p, a_, b_) for a_, b_ in ranges(add_ctrl)])
        if add_pp:
            flag("preprocessor lines the template emits into generated code (#if/#elif/#else/#endif)", "H-07",
                 e["emitted_preprocessor_lines"]["base"], e["emitted_preprocessor_lines"]["branch"],
                 [(p, a_, b_) for a_, b_ in ranges(add_pp)])
    measures["t4_templates"] = t4

    # ---- generated files
    gens = []
    regen = os.path.join("evidence", a.branch, "template-regeneration.json")
    regen_ok = os.path.exists(os.path.join(REVIEW, regen))
    for p, d in sorted(in_scope.items()):
        if kinds[p] != "generated":
            continue
        tt = p[:-3] + ".tt"
        if tt in diff:
            e = {"file": p, "template": tt, "status": "template and output changed together"}
            if regen_ok:
                e["evidence"] = regen
                e["evidence_summary"] = json.load(open(os.path.join(REVIEW, regen))).get("summary")
        else:
            has_tt = show(repo, head, tt) is not None
            e = {"file": p, "template": tt if has_tt else None,
                 "status": "generated output changed, template not changed in this diff" if has_tt
                 else "generated file (auto-generated header) changed, no template found"}
            flag("generated .cs changed without its template", "H-06", None, e["status"],
                 [(p, a_, b_) for a_, b_ in ranges(d["added"] or d["deleted"])])
        gens.append(e)
    measures["generated_files"] = gens

    # ---- tests
    test_files = sorted(p for p in in_scope if p.startswith("tests/") and p.endswith(".cs"))
    added_test_methods = []
    for p in test_files:
        d = in_scope[p]
        for h in d["hunks"]:
            for n_, t in h["added"]:
                if re.match(r"^\s*\[(Fact|Theory|Test|TestMethod)\b", t):
                    added_test_methods.append(f"{p}:{n_}")
    src_changed = sorted(p for p in in_scope if p.startswith("src/") and kinds[p] in ("source", "template", "generated"))
    claim_tests = {}
    if conf:
        for c in dossier["claims"]:
            cc = conf["details"]["claims"].get(c["id"], {})
            sk = [s["kind"] for s in cc.get("signals", [])]
            src_parts = [x for x in c.get("diff_parts", []) if x.startswith("src/")]
            claim_tests[c["id"]] = {"tier": c.get("tier"), "support_kinds": sk,
                                    "flip_or_revert_test": bool(FLIP_KINDS & set(sk)),
                                    "covers_src": bool(src_parts)}
    if src_changed and not test_files:
        flag("src changed but the diff adds or changes no test file", "H-15", None, 0, [(p, None, None) for p in src_changed])
    measures["tests"] = {"test_files_changed": test_files, "snapshot_files_changed": len(skipped),
                         "test_methods_added": len(added_test_methods), "test_method_attributes_at": added_test_methods,
                         "src_files_changed": src_changed, "claims": claim_tests,
                         "confidence_file": os.path.relpath(conf_path, REVIEW) if conf else None}

    # ---- evidence
    by_rule = {}
    for f in flags:
        by_rule[f["rule"]] = by_rule.get(f["rule"], 0) + 1
    tm = measures["methods_touched"]["methods"]
    flip_claims = [k for k, v in claim_tests.items() if v["flip_or_revert_test"]]
    summary = (f"{len(flags)} flags ({', '.join(f'{k} {v}' for k, v in sorted(by_rule.items())) or 'none'}); "
               f"{len(tm)} touched methods measured; {len(added_test_methods)} test methods added in "
               f"{len(test_files)} test files; {len(flip_claims)} of {len(claim_tests)} claims have flip/revert-test support")
    ev = {
        "check": "readability",
        "branch": a.branch,
        "base": BASE,
        "head": head[:8],
        "command": f"python3 review/scripts/readability.py --repo $MP_REPO --branch {a.branch} --write",
        "result": "pass",
        "provides": ["count"],
        "summary": summary,
        "details": {
            "result_means": "the script ran on every in-scope file; flags are signals tied to a cited rule, not verdicts",
            "diff": f"git diff {BASE}...origin/{a.branch} (old side {old[:8]})",
            "thresholds": "none from the maintainers; ours: clone window 6 normalised lines (from clone_complexity.py), "
                          "repeated added block = same normalised hunk text 2+ times, a flag fires on any increase",
            "method_parser_limits": [
                "light brace matcher over text with strings, chars, comments and preprocessor lines blanked; not a C# parser",
                "a method is a { block whose header sits directly in a type and has name( after attributes, with no = before (; "
                "property accessors count as Prop.get etc.; expression-bodied members count; local functions, lambdas, "
                "operators and indexers are not separated from their container",
                "depth counts braces only (method body = 1); braceless if/else adds none",
                "#if arms are not evaluated; both are parsed",
                "a method's line span starts at its first attribute line (e.g. [Fact]) and ends at its closing brace",
                "if/else/case/&&/|| are token counts on blanked text; `else if` counts as one else and one if",
                "base and branch methods are matched by type, name and parameter text; a changed signature shows as removed + added",
                "interpolation holes in non-raw interpolated strings: nested quotes tracked one level deep",
            ],
            "flags": flags,
            "measures": measures,
            "rules_used": "context/history.json",
        },
        "tool_versions": {"git": git(repo, "--version").strip(), "python": sys.version.split()[0]},
        "produced_by": "script",
    }
    print(summary)
    for f in flags:
        print(f"  {f['id']} {f['rule']} {f['value_base']} -> {f['value_branch']}  {f['where'][:140]}  claims={f['claims']}")
    if a.write:
        out = os.path.join(REVIEW, "evidence", a.branch, "readability.json")
        with open(out, "w") as fh:
            json.dump(ev, fh, indent=2, ensure_ascii=False)
            fh.write("\n")


if __name__ == "__main__":
    main()
